def locale_info(code: str):
    """Return (English language name, plural categories or None)."""
    try:
        loc = Locale.parse(code.replace("-", "_"))
    except (ValueError, UnknownLocaleError):
        return code, None
    cats = set(loc.plural_form.tags) | {"other"}
    name = loc.get_display_name("en") or code
    return name, [c for c in CLDR_ORDER if c in cats]


# --------------------------------------------------------------------------- #
# Validation
# --------------------------------------------------------------------------- #
def parse_single(text: str):
    res = PARSER.parse(text)
    junk = [e for e in res.body if isinstance(e, ast.Junk)]
    if junk:
        ann = junk[0].annotations[0] if junk[0].annotations else None
        detail = f"{ann.code}: {ann.message}" if ann else "unknown error"
        raise ValueError(f"FTL syntax error ({detail})")
    entries = [e for e in res.body if is_entry(e)]
    if len(entries) != 1:
        raise ValueError(f"expected exactly one FTL entry, got {len(entries)}")
    return entries[0]


def validate(src, out, cats) -> None:
    if type(out) is not type(src):
        raise ValueError("entry type changed (message vs term)")
    if out.id.name != src.id.name:
        raise ValueError(f"identifier must stay '{src.id.name}', got '{out.id.name}'")
    if (src.value is None) != (out.value is None):
        raise ValueError("entry value presence changed")
    sa = {a.id.name for a in src.attributes}
    oa = {a.id.name for a in out.attributes}
    if sa != oa:
        raise ValueError(f"attributes must be {sorted(sa)}, got {sorted(oa)}")

    s, o = Collector(), Collector()
    s.visit(src)
    o.visit(out)
    for label, a, b in (
        ("$variables", s.vars, o.vars),
        ("message references", s.msg_refs, o.msg_refs),
        ("term references", s.term_refs, o.term_refs),
        ("functions", s.funcs, o.funcs),
    ):
        if a != b:
            raise ValueError(f"{label} must be {sorted(map(str, a))}, got {sorted(map(str, b))}")

    if len(s.selects) != len(o.selects):
        raise ValueError(f"expected {len(s.selects)} select expression(s), got {len(o.selects)}")
    for ss, oo in zip(s.selects, o.selects):
        src_ids = [v for k, v in ss if k == "id"]
        out_ids = [v for k, v in oo if k == "id"]
        plural = bool(src_ids) and all(i in CLDR_ORDER for i in src_ids)
        if plural:
            if cats:
                bad = [i for i in out_ids if i not in cats]
                if bad:
                    raise ValueError(
                        f"plural variant(s) {bad} are not valid for this language; "
                        f"allowed categories: {cats}"
                    )
        elif set(ss) != set(oo):
            raise ValueError(f"selector variant keys must stay {sorted(v for _, v in ss)}")


