SYSTEM_TEMPLATE = """You are a professional software localizer. You translate Project Fluent (.ftl) \
entries from English (Canada) into {lang} (locale code: {code}).

Rules:
1. Output ONLY the translated FTL entry. No code fences, no explanations.
2. Keep the identifier and every attribute name (e.g. `.title`) exactly as in the input. \
Translate only human-readable text.
3. Everything inside {{ }} placeables stays unchanged: $variables, -terms, message references, \
functions and their arguments, string literals. The curly braces are syntax: `{{ $name }}` must \
stay `{{ $name }}` with its braces, even if you add or change quotation marks around it.
4. Select expressions: keep the selector. For plural selectors, write the variants required by \
{lang}{cats_clause}. Add or remove plural variants as the language needs. Keep the `*` default \
marker on exactly one variant (normally `[other]`). For non-plural selectors keep the variant keys \
unchanged and translate only their text.
5. Do not translate brand/product names, URLs, keyboard shortcuts, or text in backticks.
6. Keep the same multi-line structure and indentation style as the input.
7. Use a natural, neutral, polite register suitable for software UI. Follow the typographic \
conventions of {lang} (punctuation, spacing, quotation marks). If you change quotation marks \
around a placeable, keep the braces inside them, e.g. « {{ $name }} », never « $name ».

Example (target French):
Input:
items-selected =
    {{ $count ->
        [one] {{ $count }} item selected
       *[other] {{ $count }} items selected
    }}
Output:
items-selected =
    {{ $count ->
        [one] {{ $count }} élément sélectionné
       *[other] {{ $count }} éléments sélectionnés
    }}"""


def chat(args, messages) -> str:
    body = {
        "messages": messages,
        "temperature": args.temperature,
        "max_tokens": args.max_tokens,
        "chat_template_kwargs": {"enable_thinking": False},  # ignored by non-thinking models
    }
    if args.model:
        body["model"] = args.model
    req = urllib.request.Request(
        args.server.rstrip("/") + "/v1/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=args.timeout) as resp:
        data = json.load(resp)
    return data["choices"][0]["message"]["content"] or ""


def clean_output(text: str) -> str:
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL)
    text = text.strip()
    m = re.match(r"^```[a-zA-Z]*\n(.*?)\n```$", text, flags=re.DOTALL)
    if m:
        text = m.group(1)
    return text.strip()


def translate_entry(args, src, code, lang, cats):
    """Returns (translated_entry | None, error | None)."""
    comment = src.comment.content if src.comment else None
    bare = copy.deepcopy(src)
    bare.comment = None
    source_ftl = SERIALIZER.serialize_entry(bare).strip()

    cats_clause = f" (CLDR categories: {', '.join(cats)})" if cats else " (use its CLDR plural categories)"
    messages = [
        {"role": "system", "content": SYSTEM_TEMPLATE.format(lang=lang, code=code, cats_clause=cats_clause)},
        {
            "role": "user",
            "content": (
                f"Entry identifier: {entry_label(src)}\n"
                f"Translator comment: {comment or '(none)'}\n\n"
                f"Translate this entry:\n\n{source_ftl}"
            ),
        },
    ]

    last_err = None
    last_raw = ""
    for _ in range(args.retries + 1):
        try:
            raw = chat(args, messages)
        except (urllib.error.URLError, TimeoutError, OSError, KeyError, ValueError) as e:
            return None, f"request failed: {e}"
        last_raw = raw
        try:
            out = parse_single(clean_output(raw))
            validate(src, out, cats)
            out.comment = copy.deepcopy(src.comment)
            return out, None
        except ValueError as e:
            last_err = str(e)
            messages.append({"role": "assistant", "content": raw})
            messages.append(
                {"role": "user", "content": f"That output is invalid: {last_err}. Return the corrected FTL entry only."}
            )
    return None, f"{last_err} | last output: {last_raw!r}"


