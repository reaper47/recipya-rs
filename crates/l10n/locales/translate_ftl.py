def process_file(args, cache, locale, lang, cats, ref_file: Path, tgt_file: Path, failures: list) -> int:
    rel = ref_file.relative_to(Path(args.root) / args.reference)
    tag = f"[{locale}/{rel}]"

    ref_res = PARSER.parse(ref_file.read_text(encoding="utf-8"))
    tgt_text = tgt_file.read_text(encoding="utf-8") if tgt_file.exists() else ref_file.read_text(encoding="utf-8")
    tgt_res = PARSER.parse(tgt_text)

    ref_map = {entry_key(e): e for e in ref_res.body if is_entry(e)}
    tgt_index = {entry_key(e): i for i, e in enumerate(tgt_res.body) if is_entry(e)}
    hashes = {entry_label(e): entry_hash(e) for e in ref_map.values()}
    file_cache = {} if args.no_cache else cache.get(locale, {}).get(str(rel), {})

    added = 0
    todo = []
    for k, ref_e in ref_map.items():
        label = entry_label(ref_e)
        was_missing = k not in tgt_index
        if was_missing:
            tgt_res.body.append(copy.deepcopy(ref_e))
            tgt_index[k] = len(tgt_res.body) - 1
            added += 1
        tgt_e = tgt_res.body[tgt_index[k]]
        if not args.force and not was_missing:
            cached = file_cache.get(label)
            if cached == hashes[label]:
                continue  # already translated by this script, reference unchanged
            if cached is None and not tgt_e.equals(ref_e):
                continue  # translated outside this script
            # otherwise: untranslated copy, or the reference changed since last time
        if is_translatable(ref_e):
            todo.append(k)

    if not todo and not added:
        log(f"{tag} nothing to do")
        return 0

    done = 0
    new_hashes = {}
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futs = {pool.submit(translate_entry, args, ref_map[k], locale, lang, cats): k for k in todo}
        for fut in as_completed(futs):
            k = futs[fut]
            out, err = fut.result()
            label = entry_label(ref_map[k])
            if out is None:
                log(f"{tag} FAILED {label}: {err}")
                failures.append({"locale": locale, "file": str(rel), "id": label, "error": err})
            else:
                tgt_res.body[tgt_index[k]] = out
                new_hashes[label] = hashes[label]
                done += 1
                log(f"{tag} ok {label}")

    if args.dry_run:
        return done

    if done or added:
        tgt_file.parent.mkdir(parents=True, exist_ok=True)
        tgt_file.write_text(SERIALIZER.serialize(tgt_res), encoding="utf-8")
        log(f"{tag} wrote {done} translated, {added} added")
    if not args.no_cache and new_hashes:
        fc = cache.setdefault(locale, {}).setdefault(str(rel), {})
        fc.update(new_hashes)
        for lbl in [l for l in fc if l not in hashes]:
            del fc[lbl]  # entry removed from the reference
        save_cache(args.cache_path, cache)
    return done


def check_server(args) -> None:
    try:
        urllib.request.urlopen(args.server.rstrip("/") + "/health", timeout=10).read()
    except OSError as e:
        sys.exit(f"Cannot reach llama-server at {args.server} ({e}). Start it with: llama-server -m model.gguf --port 8080")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=str(SCRIPT_DIR), help="directory holding one folder per locale (default: the script's directory)")
    p.add_argument("--reference", default="en-CA")
    p.add_argument("--server", default="http://127.0.0.1:8080")
    p.add_argument("--model", default=None, help="optional model name sent to the server")
    p.add_argument("--locales", nargs="*", help="only these locales")
    p.add_argument("--skip", nargs="*", default=[], help="locales to skip")
    p.add_argument("--workers", type=int, default=1, help="parallel requests (match llama-server -np)")
    p.add_argument("--retries", type=int, default=2)
    p.add_argument("--temperature", type=float, default=0.2)
    p.add_argument("--max-tokens", type=int, default=1024)
    p.add_argument("--timeout", type=int, default=3000)
    p.add_argument("--force", action="store_true", help="retranslate entries even if they differ from the reference")
    p.add_argument("--dry-run", action="store_true", help="translate but do not write files")
    p.add_argument("--failures-file", default="l10n_failures.json")
    p.add_argument("--cache-file", default=None, help="default: .translate-cache.json next to this script")
    p.add_argument("--no-cache", action="store_true", help="ignore and don't update the cache")
    args = p.parse_args()

    root = Path(args.root)
    args.cache_path = Path(args.cache_file) if args.cache_file else SCRIPT_DIR / ".translate-cache.json"
    ref_dir = root / args.reference
    if not ref_dir.is_dir():
        sys.exit(f"Reference directory not found: {ref_dir}")
    ref_files = sorted(ref_dir.rglob("*.ftl"))
    if not ref_files:
        sys.exit(f"No .ftl files in {ref_dir}")

    locales = sorted(d.name for d in root.iterdir() if d.is_dir() and d.name != args.reference)
    if args.locales:
        locales = [l for l in locales if l in args.locales]
    locales = [l for l in locales if l not in args.skip]
    if not locales:
        sys.exit("No locales to process.")

    check_server(args)

    cache = {} if args.no_cache else load_cache(args.cache_path)
    failures: list = []
    total = 0
    try:
        for locale in locales:
            lang, cats = locale_info(locale)
            log(f"=== {locale} ({lang}) plural categories: {cats or 'unknown'}")
            for ref_file in ref_files:
                tgt_file = root / locale / ref_file.relative_to(ref_dir)
                total += process_file(args, cache, locale, lang, cats, ref_file, tgt_file, failures)
    except KeyboardInterrupt:
        log("Interrupted. Re-run to resume: translated entries are skipped automatically.")

    if failures:
        Path(args.failures_file).write_text(json.dumps(failures, indent=2, ensure_ascii=False), encoding="utf-8")
    log(f"\nDone. {total} entries translated, {len(failures)} failed"
        + (f" (see {args.failures_file})" if failures else ""))


if __name__ == "__main__":
    main()
