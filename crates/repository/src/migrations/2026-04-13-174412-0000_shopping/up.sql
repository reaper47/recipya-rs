---
--- Main tables
---
CREATE TABLE shopping_lists (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  num_items int8 NOT NULL DEFAULT 0,
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shopping_list_labels (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE users_shopping_list_labels (
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  label_id int8 NOT NULL REFERENCES shopping_list_labels (id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, label_id)
);

CREATE TABLE shopping_list_items (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shopping_list_id uuid NOT NULL REFERENCES shopping_lists (id) ON DELETE CASCADE,
  ingredient text NOT NULL CHECK (trim(ingredient) <> ''),
  quantity text CHECK (trim(quantity) <> ''),
  notes text,
  shopping_list_label_id int8 NOT NULL DEFAULT 1 REFERENCES shopping_list_labels (id) ON DELETE SET DEFAULT,
  position int4 NOT NULL DEFAULT 0 CHECK (position >= 0),
  is_checked boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE shopping_list_recipes (
  shopping_list_item_id int8 NOT NULL REFERENCES shopping_list_items (id) ON DELETE CASCADE,
  recipe_id int8 NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
  PRIMARY KEY (shopping_list_item_id, recipe_id)
);

CREATE TABLE shares_shopping_lists (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  link uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  list_id uuid NOT NULL REFERENCES shopping_lists (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP + interval '7 days'),
  last_accessed timestamptz NOT NULL DEFAULT now(),
  click_count int NOT NULL DEFAULT 0,
  UNIQUE (user_id, list_id)
);

CREATE TABLE paper_categories (
  id int2 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE paper_sizes (
  id int2 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_category_id int2 NOT NULL REFERENCES paper_categories (id) ON DELETE CASCADE,
  name text NOT NULL,
  height_mm float NOT NULL,
  width_mm float NOT NULL,
  height_in float NOT NULL,
  width_in float NOT NULL
);

