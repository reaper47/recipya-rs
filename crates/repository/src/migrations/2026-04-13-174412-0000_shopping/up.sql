CREATE TRIGGER update_shopping_lists_updated_at BEFORE
UPDATE ON shopping_lists FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column ();

CREATE TRIGGER update_shopping_list_items_updated_at BEFORE
UPDATE ON shopping_list_items FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column ();

CREATE TRIGGER update_shopping_list_items_position BEFORE INSERT ON shopping_list_items FOR EACH ROW
EXECUTE FUNCTION update_shopping_list_items_position ();
