CREATE FUNCTION update_shopping_list_items_position () RETURNS TRIGGER AS $$
BEGIN
  NEW.position := (
    SELECT COALESCE(MAX(position), 0) + 1
    FROM shopping_list_items
    WHERE shopping_list_id = NEW.shopping_list_id
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION update_shopping_list_num_items () RETURNS TRIGGER AS $$
DECLARE
  list_id UUID;
BEGIN
  IF TG_OP = 'DELETE' THEN
    list_id := OLD.shopping_list_id;
  ELSE
    list_id := NEW.shopping_list_id;
  END IF;

  UPDATE shopping_lists
  SET num_items = (
    SELECT COUNT(*)
    FROM shopping_list_items
    WHERE shopping_list_id = list_id
  )
  WHERE id = list_id;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  ELSE
    RETURN NEW;
  END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION get_default_paper_size_id () RETURNS int2 AS $$
  SELECT id
    FROM paper_sizes
    WHERE name = 'US Letter'
    LIMIT 1;
$$ LANGUAGE sql STABLE;

