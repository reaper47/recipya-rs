CREATE TABLE measurement_systems (
  id int2 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL
);

CREATE TABLE recipes (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text,
  image uuid,
  yield int2 NOT NULL DEFAULT 1,
  language char(3) NOT NULL,
  measurement_system_id int2 NOT NULL REFERENCES measurement_systems (id) ON DELETE CASCADE DEFAULT 2,
  notes text,
  source text NOT NULL DEFAULT '',
  is_favourite bool NOT NULL DEFAULT FALSE,
  rating int2 CHECK (rating BETWEEN 1 AND 5),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  fts_combined tsvector NOT NULL GENERATED ALWAYS AS (
    setweight(
      to_tsvector(get_tsv_config (LANGUAGE), coalesce(name, '')),
      'A'
    ) || setweight(
      to_tsvector(get_tsv_config (LANGUAGE), coalesce(source, '')),
      'B'
    ) || setweight(
      to_tsvector(
        get_tsv_config (LANGUAGE),
        coalesce(description, '')
      ),
      'C'
    )
  ) STORED,
  fts_category tsvector NOT NULL DEFAULT ''::tsvector,
  fts_cuisine tsvector NOT NULL DEFAULT ''::tsvector,
  fts_ingredients tsvector NOT NULL DEFAULT ''::tsvector,
  fts_instructions tsvector NOT NULL DEFAULT ''::tsvector,
  fts_keywords tsvector NOT NULL DEFAULT ''::tsvector,
  fts_name tsvector NOT NULL GENERATED ALWAYS AS (
    to_tsvector(get_tsv_config (LANGUAGE), coalesce(name, ''))
  ) STORED,
  fts_tools tsvector NOT NULL DEFAULT ''::tsvector,
  UNIQUE (name, source, yield, user_id)
);

CREATE TABLE categories (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL CHECK (lower(name) = name)
);

CREATE TABLE cuisines (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
