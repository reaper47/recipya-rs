CREATE FUNCTION init_user_data_columns () RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO counts (user_id)
        VALUES (NEW.id);
    INSERT INTO users_categories (user_id, category_id)
    SELECT
        NEW.id,
        id
    FROM
        categories
    WHERE
        name IN ('uncategorized', 'appetizers', 'bread', 'breakfasts', 'condiments', 'dessert', 'lunch', 'main dish', 'salad', 'side dish', 'snacks', 'soups', 'stews');
    INSERT INTO user_settings (user_id)
        VALUES (NEW.id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION update_recipe_count () RETURNS TRIGGER AS $$
BEGIN
    UPDATE
        counts
    SET
        recipes = recipes + 1
    WHERE
        user_id = NEW.user_id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION decrement_recipe_count () RETURNS TRIGGER AS $$
BEGIN
    UPDATE
        counts
    SET
        recipes = recipes - 1
    WHERE
        user_id = OLD.user_id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION update_category_fts_column () RETURNS TRIGGER AS $$
DECLARE
    recipe_id_to_update int8;
BEGIN
    IF TG_OP = 'DELETE' THEN
        recipe_id_to_update := OLD.recipe_id;
    ELSE
        recipe_id_to_update := NEW.recipe_id;
    END IF;

    UPDATE recipes
    SET fts_category = COALESCE(
        (SELECT to_tsvector(get_tsv_config (
        LANGUAGE), string_agg(name, ' '))
         FROM categories c
         JOIN categories_recipes cr ON cr.category_id = c.id
         WHERE cr.recipe_id = recipe_id_to_update),
        ''::tsvector)
    WHERE id = recipe_id_to_update;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$ LANGUAGE plpgsql;

