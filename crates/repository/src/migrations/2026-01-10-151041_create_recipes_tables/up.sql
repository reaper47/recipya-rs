CREATE TABLE tools (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text UNIQUE NOT NULL CHECK (lower(name) = name)
);

CREATE TABLE sections (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
