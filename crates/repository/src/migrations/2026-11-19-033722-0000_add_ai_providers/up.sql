---
--- Main tables
---
-- safety-assured:start
CREATE TABLE IF NOT EXISTS api_provider_category (
    id int2 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);
-- safety-assured:end

-- safety-assured:start
CREATE TABLE IF NOT EXISTS api_providers (
    id int4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category_id int2 NOT NULL REFERENCES api_provider_category (id) ON DELETE CASCADE
);
-- safety-assured:end

CREATE TABLE IF NOT EXISTS user_api_keys (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider_id int4 NOT NULL REFERENCES api_providers (id) ON DELETE CASCADE,
    key_ciphertext bytea NOT NULL, -- cipher|nonce|api_key
    key_version int2 NOT NULL DEFAULT 1, -- for master key rotation
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, provider_id)
);

CREATE TABLE IF NOT EXISTS user_api_providers_endpoints (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider_id int4 NOT NULL REFERENCES api_providers (id) ON DELETE CASCADE,
    endpoint_url text NOT NULL,
    UNIQUE (user_id, provider_id)
);

