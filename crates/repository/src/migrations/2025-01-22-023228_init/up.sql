CREATE OR REPLACE FUNCTION update_category_fts_func ()
  RETURNS TRIGGER
  AS $$
BEGIN
  UPDATE
    recipes
  SET
    fts_category = COALESCE((
      SELECT
        to_tsvector(get_tsv_config (
            LANGUAGE), string_agg(name, ''))
      FROM categories c
      JOIN categories_recipes cr ON cr.category_id = c.id
      WHERE
        cr.recipe_id = NEW.recipe_id), ''::tsvector)
  WHERE
    id = NEW.recipe_id;
  RETURN NULL;
END;
$$
LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION update_cuisine_fts_func ()
  RETURNS TRIGGER
  AS $$
DECLARE
    recipe_id_to_update BIGINT;
    recipe_language     CHAR(3);
BEGIN
    IF TG_OP = 'DELETE' THEN
        recipe_id_to_update := OLD.recipe_id;
    ELSE
        recipe_id_to_update := NEW.recipe_id;
    END IF;

    SELECT language
    INTO recipe_language
    FROM recipes
    WHERE id = recipe_id_to_update;

    UPDATE recipes
    SET fts_cuisine = COALESCE(
            (SELECT to_tsvector(get_tsv_config(recipe_language), string_agg(name, ' ' ORDER BY name))
             FROM cuisines c
                      JOIN cuisines_recipes cr ON cr.cuisine_id = c.id
             WHERE cr.recipe_id = NEW.recipe_id),
            ''::tsvector)
    WHERE id = recipe_id_to_update;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$
LANGUAGE plpgsql;

