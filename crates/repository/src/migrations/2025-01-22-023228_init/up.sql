CREATE TABLE recipes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text,
  image uuid,
  yield smallint NOT NULL DEFAULT 1,
  language CHAR
(3) NOT NULL,
  measurement_system_id smallint NOT NULL REFERENCES measurement_systems (id) ON DELETE CASCADE DEFAULT 2,
  notes text,
  source text NOT NULL DEFAULT '',
  is_favourite bool NOT NULL DEFAULT FALSE,
  rating smallint CHECK (rating BETWEEN 1 AND 5),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  fts_combined tsvector NOT NULL GENERATED ALWAYS AS (setweight(to_tsvector(get_tsv_config (
  LANGUAGE), coalesce(name, '')), 'A') || setweight(to_tsvector(get_tsv_config (
  LANGUAGE), coalesce(source, '')), 'B') || setweight(to_tsvector(get_tsv_config (
  LANGUAGE), coalesce(description, '')), 'C')) STORED,
