CREATE OR REPLACE FUNCTION delete_orphaned_nutrition () RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM nutrition
    WHERE id = OLD.nutrition_id
        AND NOT EXISTS (
            SELECT
                1
            FROM
                nutrition_per_100g
            WHERE
                nutrition_id = OLD.nutrition_id)
        AND NOT EXISTS (
            SELECT
                1
            FROM
                nutrition_per_serving
            WHERE
                nutrition_id = OLD.nutrition_id);
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

