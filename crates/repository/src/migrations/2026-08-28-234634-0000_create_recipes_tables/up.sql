CREATE FUNCTION get_tsv_config (lang char(3)) RETURNS regconfig AS $$
BEGIN
    RETURN CASE lang
    WHEN 'ara' THEN
        'arabic'
    WHEN 'cat' THEN
        'catalan'
    WHEN 'dan' THEN
        'danish'
    WHEN 'deu' THEN
        'german'
    WHEN 'eng' THEN
        'english'
    WHEN 'ell' THEN
        'greek'
    WHEN 'fin' THEN
        'finnish'
    WHEN 'fra' THEN
        'french'
    WHEN 'hin' THEN
        'hindi'
    WHEN 'hun' THEN
        'hungarian'
    WHEN 'hye' THEN
        'armenian'
    WHEN 'ind' THEN
        'indonesian'
    WHEN 'ita' THEN
        'italian'
    WHEN 'lit' THEN
        'lithuanian'
    WHEN 'nep' THEN
        'nepali'
    WHEN 'nld' THEN
        'dutch'
    WHEN 'por' THEN
        'portuguese'
    WHEN 'ron' THEN
        'romanian'
    WHEN 'rus' THEN
        'russian'
    WHEN 'spa' THEN
        'spanish'
    WHEN 'srp' THEN
        'serbian'
    WHEN 'swe' THEN
        'swedish'
    WHEN 'tam' THEN
        'tamil'
    WHEN 'tur' THEN
        'turkish'
    WHEN 'yid' THEN
        'yiddish'
    ELSE
        'simple'
    END;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

